#!/usr/bin/env python3
"""Builds main/i18n_sr.h from main/lang/sr.txt.

sr.txt has one translation per line:  English text|Srpski tekst
(UTF-8, '#' starts a comment line). Serbian letters are turned into the
font's single-byte glyph codes (see gen_font.py) so text width = strlen.
"""
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'main', 'lang', 'sr.txt')
OUT = os.path.join(HERE, '..', 'main', 'i18n_sr.h')
MAP = {'č': 0x84, 'ć': 0x85, 'đ': 0x86, 'š': 0x87, 'ž': 0x88,
       'Č': 0x89, 'Ć': 0x8a, 'Đ': 0x8b, 'Š': 0x8c, 'Ž': 0x8d}

def c_str(s, device):
    out, prev_hex = '"', False
    for ch in s:
        if device and ch in MAP:
            out += '\\x%02x' % MAP[ch]; prev_hex = True; continue
        if ord(ch) > 126:
            if device: sys.exit('unsupported char %r in %r' % (ch, s))
            b = ch.encode()
            out += ''.join('\\x%02x' % x for x in b); prev_hex = True; continue
        if prev_hex and ch in '0123456789abcdefABCDEF':
            out += '" "'
        prev_hex = False
        out += {'"': '\\"', '\\': '\\\\'}.get(ch, ch)
    return out + '"'

pairs = {}
for n, line in enumerate(open(SRC, encoding='utf-8'), 1):
    line = line.rstrip('\n')
    if not line.strip() or line.startswith('#'): continue
    if '|' not in line: sys.exit('sr.txt:%d: missing |' % n)
    en, sr = line.split('|', 1)
    if en in pairs: sys.exit('sr.txt:%d: duplicate %r' % (n, en))
    pairs[en] = sr
keys = sorted(pairs, key=lambda k: k.encode())
with open(OUT, 'w') as f:
    f.write('/* Generated by tools/gen_i18n.py from main/lang/sr.txt - do not edit. */\n')
    f.write('#pragma once\n/* Sorted by English text (bytewise) for binary search. */\n')
    f.write('static const char *const i18n_sr[][2] = {\n')
    for k in keys:
        f.write('    { %s, %s },\n' % (c_str(k, False), c_str(pairs[k], True)))
    f.write('};\n#define I18N_SR_COUNT %d\n' % len(keys))
print('wrote', OUT, len(keys), 'strings')
