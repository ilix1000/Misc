SMALL = {  # 8x8 for list rows / status bar
'LOCK': ["..kkkk..", ".k....k.", ".k....k.", "kkkkkkkk", "kyyyyyyk", "kyykkyyk", "kyyyyyyk", "kkkkkkkk"],
'SMALLSTAR': ["...y....", "...y....", "..yyy...", "yyyyyyy.", ".yyyyy..", "..yyy...", ".yy.yy..", ".y...y.."],
}
def check(name, rows, n):
    assert len(rows) == n, (name, len(rows))
    for r in rows:
        assert len(r) == n, (name, r, len(r))
        for ch in r: assert ch == '.' or ch in PAL, (name, ch)
for k, v in ICONS.items(): check(k, v, 16)
for k, v in SMALL.items(): check(k, v, 8)
def swap565(rgb):
    r, g, b = rgb
    c = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    c = ((c << 8) | (c >> 8)) & 0xFFFF
    return 1 if c == 0 else c   # 0 is reserved for "transparent"
out = ["/* Generated by tools/gen_icons.py - do not edit. Original pixel art. */",
       "#pragma once", "#include <stdint.h>", "",
       "/* RGB565 (byte-swapped for the panel), 0 = transparent. */"]
def emit(name, rows, n):
    vals = [0 if ch == '.' else swap565(PAL[ch]) for r in rows for ch in r]
    out.append(f"static const uint16_t icon_{name.lower()}[{n * n}] = {{")
    for i in range(0, len(vals), 16):
        out.append("    " + ", ".join("0x%04x" % v for v in vals[i:i + 16]) + ",")
    out.append("};")
for k, v in ICONS.items(): emit(k, v, 16)
for k, v in SMALL.items(): emit(k, v, 8)
open(sys.argv[1], "w").write("\n".join(out) + "\n")
if len(sys.argv) > 2:
    from PIL import Image
    S = 8
    allicons = list(ICONS.items()) + list(SMALL.items())
    img = Image.new("RGB", (len(allicons) * 18 * S, 18 * S), (40, 44, 70))
    for i, (k, rows) in enumerate(allicons):
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch != '.':
                    for dy in range(S):
                        for dx in range(S):
                            img.putpixel((i * 18 * S + S + x * S + dx, S + y * S + dy), PAL[ch])
    img.save(sys.argv[2])
